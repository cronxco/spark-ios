#!/usr/bin/env python3
"""Build SparkUI's Font Awesome glyphs from Packages/SparkUI/icons.json.

Writes two files:
  - Packages/SparkUI/Sources/SparkUI/Theme/SparkIcon.swift (the enum)
  - Packages/SparkUI/Sources/SparkUI/Resources/Fonts/FontAwesome6Free-Solid-Spark.ttf
    (the Solid font, cut down to the glyphs the manifest names)

Usage:
  npm pack @fortawesome/fontawesome-free@6.7.2 && tar xzf fortawesome-fontawesome-free-6.7.2.tgz
  pip install fonttools
  scripts/build-icons.py package

The version in the manifest must match the package, so the codepoints and the
font always come from the same release.
"""

import json
import pathlib
import sys

from fontTools import subset

ROOT = pathlib.Path(__file__).resolve().parent.parent
MANIFEST = ROOT / "Packages/SparkUI/icons.json"
SWIFT_OUT = ROOT / "Packages/SparkUI/Sources/SparkUI/Theme/SparkIcon.swift"
FONT_OUT = ROOT / "Packages/SparkUI/Sources/SparkUI/Resources/Fonts/FontAwesome6Free-Solid-Spark.ttf"


def main() -> None:
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    package = pathlib.Path(sys.argv[1])
    manifest = json.loads(MANIFEST.read_text())
    meta = json.loads((package / "package.json").read_text())
    if meta["version"] != manifest["fontawesome"]:
        sys.exit(f"Manifest pins {manifest['fontawesome']}, package is {meta['version']}")

    families = json.loads((package / "metadata/icon-families.json").read_text())
    codepoints = {}
    for concept, name in manifest["icons"].items():
        entry = families.get(name)
        if entry is None:
            sys.exit(f"{concept}: no Font Awesome icon named {name}")
        codepoints[concept] = (name, entry["unicode"])

    options = subset.Options()
    options.layout_features = []
    options.name_IDs = ["*"]
    options.notdef_outline = True
    font = subset.load_font(str(package / "webfonts/fa-solid-900.ttf"), options)
    subsetter = subset.Subsetter(options)
    subsetter.populate(unicodes=sorted({int(code, 16) for _, code in codepoints.values()}))
    subsetter.subset(font)
    cmap = font.getBestCmap()
    missing = [c for c, (_, code) in codepoints.items() if int(code, 16) not in cmap]
    if missing:
        sys.exit(f"Not in the Solid font: {', '.join(missing)}")
    font.save(str(FONT_OUT))

    cases = "\n".join(f"    case {concept}" for concept in codepoints)
    glyphs = "\n".join(
        f"        case .{concept}: \"\\u{{{code}}}\" // fas.{name}"
        for concept, (name, code) in codepoints.items()
    )
    SWIFT_OUT.write_text(f"""// Generated by scripts/build-icons.py from Packages/SparkUI/icons.json.
// Do not edit by hand: change the manifest and run the script.
// Font Awesome Free {manifest['fontawesome']}, Solid. Font: SIL OFL 1.1. Icons: CC BY 4.0.

/// One Spark concept, one Font Awesome Solid glyph (`docs/design-language.md`
/// section 6). Several concepts can share a glyph. Draw one with `SparkGlyph`.
public enum SparkIcon: String, CaseIterable, Sendable {{
{cases}

    /// The glyph's character in the bundled font.
    public var glyph: String {{
        switch self {{
{glyphs}
        }}
    }}
}}
""")
    print(f"{len(codepoints)} icons, {FONT_OUT.stat().st_size} bytes")


if __name__ == "__main__":
    main()
